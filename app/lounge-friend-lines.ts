import type { FeteKind } from './lounge-social-defs.ts';

export type FriendLineSet = {
  /** 이 친구 NPC의 임시 성격 (자리 채움). */
  archetype: string;
  /** ♥10 칭호. */
  title: string;
  /** 시간대 인사. */
  greet: Record<TimeOfDay, string[]>;
  /** 날씨 인사 (없으면 시간대 인사). */
  weather: Partial<Record<Weather, string[]>>;
  /** 계절 이야기. */
  season: Record<Season, string[]>;
  /** 말 건 사람이 하는 일에 대한 반응. */
  doing: { farm: string[]; fish: string[]; item: string[] };
  /** 다른 친구 소식 전하기 ({friend}, {news}). */
  gossip: string[];
  /** 하트 수 이상일 때만. */
  hearts: Record<2 | 4 | 6 | 8 | 10, string[]>;
  /** theirs: 이 친구 생일 / yours: 말 건 사람 생일. */
  birthday: { theirs: string[]; yours: string[] };
  /** 축제 날 (kind별) · holiday: 그 밖의 명절. */
  festival: Record<FeteKind, string[]> & { holiday: string[] };
  /** 부탁이 있을 때 첫마디. */
  request: string[];
  /** 선택지 대화: 질문과 [내 대답, 친구 반응] 두세 쌍. */
  smallTalk: { q: string; choices: [string, string][] }[];
};


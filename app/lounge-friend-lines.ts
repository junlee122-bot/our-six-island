/**
 * ============================================================================
 *  친구 NPC 대사집 (FRIEND NPC LINES) — 이 파일 하나만 고치면 돼요.
 * ============================================================================
 *
 *  범타듀 밸리에서 접속하지 않은(쉬는) 친구는 마을을 걸어 다니는 NPC가 되고,
 *  다가가서 E를 누르면 여기 적힌 대사로 이야기해요.
 *
 *  지금 들어 있는 대사는 **자리 채움(PLACEHOLDER)** 이에요. 실제 친구들의
 *  말투를 모르기 때문에, 친구마다 서로 다른 "따뜻하고 무난한 성격"을 하나씩
 *  정해 두고 그 성격에 맞춰 썼어요(archetype 참고). 진짜 친구의 말버릇,
 *  유행어, 서로만 아는 농담으로 마음껏 바꿔 주세요.
 *
 *  고치는 법
 *  - 배열 안의 문장을 바꾸거나 더하고 빼면 끝이에요. 개수 제한은 없지만
 *    한 줄은 60자 안쪽이 대화창에 보기 좋아요. 이모지는 쓰지 않아요.
 *  - 비워 둔 배열([])이 있으면 그 상황에서는 다른 종류의 대사가 나와요.
 *  - 문장 속 {이름표}는 게임이 채워요:
 *      {me}      말을 건 사람 이름 (예: 승준)
 *      {name}    이 친구 이름
 *      {season}  지금 계절 (봄·여름·가을·겨울)
 *      {item}    말 건 사람이 손에 든 물건 이름
 *      {friend}  소문의 주인공 친구 이름
 *      {news}    어제·오늘 마을 소식 한 줄 (예: 도원이 민서의 밭에 물을 줬어)
 *      {holiday} 오늘 명절 이름
 *    이름 바로 뒤에 조사(이/가, 은/는)를 붙이면 받침에 따라 어색할 수 있어요.
 *    "{me}, 안녕!"처럼 쉼표나 문장부호를 붙여 주세요.
 *  - smallTalk는 대화 끝에 나오는 선택지예요. [내 대답, 친구의 반응] 짝이고,
 *    하루에 친구마다 한 번, 고르면 하트(추억)가 조금 쌓여요.
 *  - hearts는 그 하트 수 이상일 때만 나오는 대사예요(♥6부터는 특별한 대화).
 *  - title은 그 친구와 ♥10이 된 사람이 받는 칭호예요.
 *
 *  친구가 직접 쓰는 대사
 *  - 게임 안 "친구 사이(L) → 내 대사 쓰기"에서 각자 자기 NPC 대사를 최대
 *    10줄(한 줄 40자)까지 쓸 수 있어요. 그 대사가 있으면 이 파일의 대사보다
 *    먼저, 자주 나와요. 이 파일을 고치지 않아도 친구들이 직접 채울 수 있어요.
 *
 *  순서: 0 도원, 1 강재, 2 민서, 3 승준, 4 민재, 5 재민, 6 호현
 *  (선물·생일 같은 취향은 lounge-calendar.ts의 FRIEND_PROFILES에 있어요.)
 * ============================================================================
 */
